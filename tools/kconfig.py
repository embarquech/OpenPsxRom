#!/usr/bin/env python3
"""OpenPsxRom build configuration (Kconfig, as the Linux kernel's make menuconfig).

  python tools/kconfig.py menuconfig        edit .config in a text UI (pip install kconfiglib,
                                            and windows-curses on Windows); run it from a real
                                            console (cmd, PowerShell, Windows Terminal, xterm)
  python tools/kconfig.py defconfig         rewrite configs/defconfig from the Kconfig defaults
  python tools/kconfig.py header CFG OUT    write OUT (build/config.h): configs/defconfig, then
                                            CFG (.config) if it exists; no kconfiglib needed
Then: make cart -> build/cart.rom, for the cartridge type chosen in the menu.

Every option becomes '#define CONFIG_NAME 1' or '0' (strings: the quoted string), so the code
tests them with '#if CONFIG_NAME' or 'if (CONFIG_NAME)'."""
import os, re, sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
KCONFIG = os.path.join(ROOT, 'Kconfig')
DEFCONFIG = os.path.join(ROOT, 'configs', 'defconfig')


def version():
    m = re.search(r'#define OPENROM_VERSION "([^"]+)"', open(os.path.join(ROOT, 'src', 'rom.h')).read())
    return m.group(1) if m else '?'


def kconf():
    try:
        import kconfiglib
    except ImportError:
        sys.exit('menuconfig needs kconfiglib: pip install kconfiglib' +
                 (' windows-curses' if os.name == 'nt' else ''))
    os.environ['OPENROM_VERSION'] = version()
    return kconfiglib.Kconfig(KCONFIG)


def read_config(path, vals):
    for line in open(path, encoding='utf-8'):
        line = line.strip()
        m = re.match(r'CONFIG_(\w+)=(.*)', line)
        if m:
            vals[m.group(1)] = m.group(2)
        m = re.match(r'# CONFIG_(\w+) is not set', line)
        if m:
            vals[m.group(1)] = 'n'


def header(cfg, out):
    vals = {}
    read_config(DEFCONFIG, vals)
    if os.path.exists(cfg):
        read_config(cfg, vals)
    lines = ['/* generated by tools/kconfig.py from configs/defconfig%s: do not edit */'
             % (' and ' + os.path.basename(cfg) if os.path.exists(cfg) else '')]
    for k, v in sorted(vals.items()):
        if v in ('y', 'n'):
            lines.append('#define CONFIG_%s %d' % (k, v == 'y'))
        else:
            lines.append('#define CONFIG_%s %s' % (k, v))
    text = '\n'.join(lines) + '\n'
    if not os.path.exists(out) or open(out).read() != text:     # unchanged: no rebuild
        os.makedirs(os.path.dirname(out) or '.', exist_ok=True)
        open(out, 'w').write(text)


def main():
    a = sys.argv[1:]
    if not a:
        sys.exit(__doc__)
    if a[0] == 'menuconfig':
        os.chdir(ROOT)
        os.environ.setdefault('KCONFIG_CONFIG', '.config')
        os.environ['MENUCONFIG_STYLE'] = os.environ.get('MENUCONFIG_STYLE', 'aquatic')
        k = kconf()
        import menuconfig                   # no .config yet: starts from the Kconfig defaults
        menuconfig.menuconfig(k)
        print('\nnow: make cart  (-> build/cart.rom)')
    elif a[0] == 'defconfig':
        k = kconf()
        os.makedirs(os.path.dirname(DEFCONFIG), exist_ok=True)
        k.write_config(DEFCONFIG, header='# OpenPsxRom default configuration (python tools/kconfig.py defconfig)\n')
    elif a[0] == 'header' and len(a) == 3:
        header(a[1], a[2])
    else:
        sys.exit(__doc__)


if __name__ == '__main__':
    main()
